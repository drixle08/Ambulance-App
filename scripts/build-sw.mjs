// Generate public/sw.js for this build (runs after `next build`, see package.json).
//
// Fills scripts/sw.template.js with:
//   buildId    — .next/BUILD_ID (derived from the app's content, so it does not
//                change when only the worker does)
//   version    — hash of everything below plus the template: names this build's
//                cache, and makes sw.js change whenever the app or the worker
//                changes, which is what makes browsers install the update
//   pages     — every page route (from Next's manifests), plus the CPG viewer shell
//   assets     — every file under .next/static, plus the PWA manifest and icons
//   reference  — reference PDFs: which exist, and which to save after install
//
// Fails the build if a dashboard tool has no precached page, so a new tool
// can't silently ship without offline support.

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const NEXT = path.join(ROOT, ".next");
const readJson = (p) => JSON.parse(fs.readFileSync(p, "utf8"));

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const buildId = fs.readFileSync(path.join(NEXT, "BUILD_ID"), "utf8").trim();

// Pages: static app routes + prerendered dynamic routes, minus APIs,
// internal pages, dynamic segments, files and redirect sources.
const appRoutes = Object.values(readJson(path.join(NEXT, "app-path-routes-manifest.json")));
const prerendered = Object.keys(readJson(path.join(NEXT, "prerender-manifest.json")).routes);
const redirectSources = new Set(readJson(path.join(NEXT, "routes-manifest.json")).redirects.map((r) => r.source));
const pages = [...new Set([...appRoutes, ...prerendered])]
  .filter((route) =>
    !route.startsWith("/api/") &&
    !route.startsWith("/_") &&
    !route.includes("[") &&
    !path.extname(route) &&
    !redirectSources.has(route)
  )
  .concat("/cpg/view")
  .sort();

// Assets: all built static files + the public files the browser loads itself.
const staticFiles = walk(path.join(NEXT, "static")).map(
  (file) => "/_next/static/" + path.relative(path.join(NEXT, "static"), file).split(path.sep).join("/")
);
const publicFiles = ["/manifest.webmanifest", "/favicon.ico"];
const iconsDir = path.join(ROOT, "public", "icons");
if (fs.existsSync(iconsDir)) {
  for (const file of fs.readdirSync(iconsDir)) publicFiles.push(`/icons/${file}`);
}
const assets = [...new Set([...staticFiles, ...publicFiles])].sort();

// Reference PDFs.
const referenceDir = path.join(ROOT, "public", "reference");
const referenceFiles = walk(referenceDir)
  .filter((file) => file.endsWith(".pdf"))
  .map((file) => "/reference/" + path.relative(referenceDir, file).split(path.sep).join("/"))
  .sort();
const editions = readJson(path.join(ROOT, "lib", "cpgEdition.json"));
const cpgPdf = `/reference/cpg/${editions.editions[editions.current].pdfFile}`;
if (!referenceFiles.includes(cpgPdf)) throw new Error(`Shipped CPG PDF not found: public${cpgPdf}`);

// Every tool on the dashboard must have a precached page.
const dataSource = fs.readFileSync(path.join(ROOT, "app", "(app)", "dashboard", "data.ts"), "utf8");
const toolRoutes = [...dataSource.matchAll(/href:\s*"(\/[^"]+)"/g)].map((m) => m[1]);
const missing = toolRoutes.filter((route) => !pages.includes(route));
if (missing.length) {
  throw new Error(`Dashboard tools with no precached page (offline would fail): ${missing.join(", ")}`);
}

const template = fs.readFileSync(path.join(ROOT, "scripts", "sw.template.js"), "utf8");
if (!template.includes("/*__CONFIG__*/ null")) throw new Error("CONFIG placeholder missing from scripts/sw.template.js");

const contents = { buildId, pages, assets, reference: { files: referenceFiles, precache: [cpgPdf] } };
// A worker-only change keeps the same buildId; giving it the same cache name as
// the worker in charge would let a failed install delete the cache in use.
const version = createHash("sha256").update(template).update(JSON.stringify(contents)).digest("hex").slice(0, 12);
const config = { ...contents, version };
const header = "// GENERATED by scripts/build-sw.mjs from scripts/sw.template.js — do not edit.\n";
fs.writeFileSync(path.join(ROOT, "public", "sw.js"), header + template.replace("/*__CONFIG__*/ null", JSON.stringify(config)));

console.log(
  `[sw] build ${buildId}, worker ${version}: ${pages.length} pages, ${assets.length} assets precached; ` +
  `${referenceFiles.length} reference PDFs (${config.reference.precache.join(", ")} saved after install)`
);
