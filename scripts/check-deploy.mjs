// Post-deploy check: is offline support actually live on a deployment?
//
//   npm run check:deploy -- https://your-app.vercel.app
//
// Fails (exit 1) unless:
//   - /sw.js is served (200, JavaScript), is the build-generated worker (not a
//     stale hand-written one), and is not HTTP-cacheable
//   - every page and asset in its precache list returns 200 without redirect
//     (one missing file makes the whole install fail on every device)
//   - each reference PDF it lists is reachable
// A missing /sw.js shows nothing visibly wrong in the app, so run this after
// every production deploy.

const base = (process.argv[2] || "").replace(/\/$/, "");
if (!/^https?:\/\//.test(base)) {
  console.error("Usage: npm run check:deploy -- https://your-app.example");
  process.exit(2);
}

const problems = [];
const fail = (msg) => problems.push(msg);

async function head(path) {
  const res = await fetch(base + path, { redirect: "manual" });
  await res.arrayBuffer().catch(() => {});
  return res;
}

const sw = await fetch(`${base}/sw.js`, { redirect: "manual" });
const swText = await sw.text();
if (sw.status !== 200) fail(`/sw.js returned ${sw.status} — the app has NO service worker (no offline, no updates)`);
if (!/javascript/.test(sw.headers.get("content-type") || "")) fail(`/sw.js content-type is ${sw.headers.get("content-type")}`);
if (!swText.startsWith("// GENERATED by scripts/build-sw.mjs")) fail("/sw.js is not the build-generated worker (build step skipped? stale file?)");
const cacheControl = sw.headers.get("cache-control") || "";
if (!/no-cache|no-store|max-age=0/.test(cacheControl)) fail(`/sw.js is HTTP-cacheable (${cacheControl || "no Cache-Control"}) — updates may be missed`);

let config = null;
const match = swText.match(/const CONFIG = (\{.*?\});\n/s);
if (match) config = JSON.parse(match[1]);
else if (sw.status === 200) fail("Could not read the precache list from /sw.js");

if (config) {
  const urls = [...config.pages, ...config.assets];
  const bad = [];
  for (let i = 0; i < urls.length; i += 8) {
    const batch = urls.slice(i, i + 8);
    const results = await Promise.all(batch.map(async (u) => [u, await head(u)]));
    for (const [u, res] of results) if (res.status !== 200) bad.push(`${u} → ${res.status}`);
  }
  if (bad.length) fail(`Precache entries not servable (install will fail on every device):\n    ${bad.join("\n    ")}`);
  for (const pdf of config.reference.files) {
    const res = await fetch(base + pdf, { method: "HEAD" });
    if (res.status !== 200) fail(`Reference PDF ${pdf} → ${res.status}`);
  }
  console.log(`build ${config.buildId}: ${config.pages.length} pages + ${config.assets.length} assets checked; sw.js Cache-Control: ${cacheControl}`);
}

if (problems.length) {
  console.error(`\nOFFLINE SUPPORT CHECK FAILED for ${base}:\n- ${problems.join("\n- ")}`);
  process.exitCode = 1; // not process.exit(): let open fetch handles close (Windows libuv)
} else {
  console.log(`Offline support check passed for ${base}.`);
}
